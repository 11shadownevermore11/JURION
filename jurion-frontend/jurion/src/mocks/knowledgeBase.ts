export function findChunk(chunkId: string) {
  return CHUNKS.find((c) => c.chunkId === chunkId) ?? null;
}

export function findDocument(fileId: string) {
  return DOCUMENTS.find((d) => d.fileId === fileId) ?? null;
}

export function chunkText(chunk: MockChunk): string {
  const doc = findDocument(chunk.fileId);
  if (!doc) return "";
  return doc.lines.slice(chunk.lineStart - 1, chunk.lineEnd).join("\n");
}
